/**
 * Builds an accessible inline SVG icon using Lucide-style paths.
 */
export function createSvgIcon(name, size = 16) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('class', 'ui-icon');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');

  const shapes = ICON_PATHS[name] || [];
  for (const [tag, attrs] of shapes) {
    const node = document.createElementNS(SVG_NS, tag);
    for (const [attr, value] of Object.entries(attrs)) {
      node.setAttribute(attr, value);
    }
    svg.appendChild(node);
  }
  return svg;
}

export function setButtonIconLabel(button, iconName, labelText, iconAfter = false) {
  button.innerHTML = '';
  const icon = createSvgIcon(iconName);
  const span = document.createElement('span');
  span.textContent = labelText;
  if (iconAfter) {
    button.append(span, icon);
  } else {
    button.append(icon, span);
  }
}
